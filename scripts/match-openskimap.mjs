// Matches each seeded mountain to the nearest public/data/ski-areas.json entry
// within 8 km whose name is similar, and writes
// supabase/migrations/003_openskimap_ids.sql to set openskimap_id and snap
// lat/lon to the OpenSkiMap point. Unmatched mountains are printed (and logged
// in DECISIONS.md by hand) and stay as seeded.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { SEED } from './seed-data.mjs'

const areas = JSON.parse(readFileSync(fileURLToPath(new URL('../public/data/ski-areas.json', import.meta.url)), 'utf8'))
const MAX_KM = 8
const FILLER = new Set(['ski', 'resort', 'area', 'mountain', 'mount', 'mont', 'mt', 'the', 'and', 'station', 'de', 'la', 'le', 'at', 'club', 'peak', 'center', 'centre', 'basin', 'valley', 'snow'])
const words = (s) => s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').split(/[^a-z0-9]+/).filter(Boolean)
const key = (s) => words(s).filter((w) => !FILLER.has(w))

function km(a, b) {
  const R = 6371, rad = Math.PI / 180
  const dLat = (b.lat - a.lat) * rad, dLon = (b.lon - a.lon) * rad
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLon / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(h))
}
// Similar = shares a distinctive word, or (when a name is all filler, like
// "Blue Mountain") contains the other's full word list.
function similar(a, b) {
  const ka = key(a), kb = key(b)
  if (ka.length && kb.length) return ka.some((w) => kb.includes(w))
  const wa = words(a), wb = words(b)
  return wa.every((w) => wb.includes(w)) || wb.every((w) => wa.includes(w))
}

const q = (s) => `'${s.replace(/'/g, "''")}'`
const lines = [], unmatched = []
for (const [name, , , lat, lon] of SEED) {
  const best = areas
    .map((a) => ({ a, d: km({ lat, lon }, a) }))
    .filter(({ a, d }) => d <= MAX_KM && similar(name, a.name))
    .sort((x, y) => x.d - y.d)[0]
  if (!best) { unmatched.push(name); continue }
  console.log(`${name.padEnd(20)} → ${best.a.name} (${best.d.toFixed(1)} km)`)
  lines.push(`update public.ski_mountains set openskimap_id = ${q(best.a.id)}, lat = ${best.a.lat}, lon = ${best.a.lon} where name = ${q(name)} and openskimap_id is null;  -- ${best.a.name}, ${best.d.toFixed(1)} km`)
}
writeFileSync(
  fileURLToPath(new URL('../supabase/migrations/003_openskimap_ids.sql', import.meta.url)),
  `-- Link seeded mountains to OpenSkiMap and snap them to its points.\n-- Generated by scripts/match-openskimap.mjs.\nbegin;\n\n${lines.join('\n')}\n\ncommit;\n`
)
console.log(`\n${lines.length} matched, ${unmatched.length} unmatched${unmatched.length ? ': ' + unmatched.join(', ') : ''}`)
