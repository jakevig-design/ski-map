// Writes supabase/migrations/002_seed.sql from scripts/seed-data.mjs.
// One trip per skied mountain with year = null (Tremblant gets three); planned
// mountains get none. Years are never invented — Jake fills them in.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { SEED } from './seed-data.mjs'

const q = (s) => `'${s.replace(/'/g, "''")}'`
const rows = SEED.map(([n, r, c, lat, lon, st]) => `  (${q(n)}, ${q(r)}, ${q(c)}, ${lat}, ${lon}, ${q(st)})`)
const trips = SEED.filter((s) => s[6] > 0).map(([n, , , , , , t]) => `  (${q(n)}, ${t})`)
const sql = `-- Jake's mountains: 26 skied, 3 planned. Generated by scripts/build-seed.mjs.
-- Safe to run once; re-running skips mountains that already exist (by name).
begin;

insert into public.ski_mountains (name, region, country, lat, lon, status)
select v.name, v.region, v.country, v.lat, v.lon, v.status
from (values
${rows.join(',\n')}
) as v(name, region, country, lat, lon, status)
where not exists (select 1 from public.ski_mountains m where m.name = v.name);

insert into public.ski_trips (mountain_id, year)
select m.id, null
from (values
${trips.join(',\n')}
) as v(name, trips)
join public.ski_mountains m on m.name = v.name
cross join generate_series(1, v.trips)
where not exists (select 1 from public.ski_trips t where t.mountain_id = m.id);

commit;
`
writeFileSync(fileURLToPath(new URL('../supabase/migrations/002_seed.sql', import.meta.url)), sql)
console.log(`${SEED.length} mountains, ${SEED.reduce((a, s) => a + s[6], 0)} trips → 002_seed.sql`)
